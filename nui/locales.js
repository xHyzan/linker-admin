let activeLocale = "pt-BR";
let staticCopy;

function t(source, values = {}) {
  const key = String(source ?? "");
  const strings = LINKER_ADMIN_LOCALES[activeLocale];
  const translation = Object.prototype.hasOwnProperty.call(strings, key) ? strings[key] : key;
  return translation.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  );
}

function applyLocale(locale) {
  activeLocale = Object.prototype.hasOwnProperty.call(LINKER_ADMIN_LOCALES, locale) ? locale : "pt-BR";
  document.documentElement.lang = activeLocale;
  if (!staticCopy) {
    staticCopy = [];
    const walker = document.createTreeWalker(document.querySelector(".shell"), NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      const source = node.nodeValue;
      if (source.trim()) staticCopy.push(() => { node.nodeValue = source.replace(source.trim(), () => t(source.trim())); });
    }
    for (const node of document.querySelectorAll(".shell [placeholder], .shell [aria-label], .picker [placeholder], .picker [aria-label]")) {
      for (const attr of ["placeholder", "aria-label"]) {
        const source = node.getAttribute(attr);
        if (source) staticCopy.push(() => node.setAttribute(attr, t(source)));
      }
    }
    for (const node of document.querySelectorAll("#picker-close, #picker-filter")) {
      for (const text of (node.tagName === "INPUT" ? node.parentElement : node).childNodes) {
        if (text.nodeType !== Node.TEXT_NODE || !text.nodeValue.trim()) continue;
        const source = text.nodeValue;
        staticCopy.push(() => { text.nodeValue = source.replace(source.trim(), () => t(source.trim())); });
      }
    }
  }
  staticCopy.forEach((translate) => translate());
}
